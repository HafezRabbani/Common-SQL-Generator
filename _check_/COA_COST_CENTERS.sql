SELECT CC.COD_CC_CCNTR
      ,CC.DES_CC_CCNTR
      ,CC.FLG_OPN_CCNTR
      ,CC.ASPRJ_COD_PRJ_ASPRJ
      ,APPS.MAM_WRAPPER_PKG.GET_FARSI_MEANING_AND_COD_FUN(P_TABLE  => 'coa_cost_centers'
                                                         ,P_COLUMN => 'LKP_TYP_CC_CCNTR'
                                                         ,P_VALUE  => CC.LKP_TYP_CC_CCNTR) AS LKP_TYP_CC
      ,APPS.MAM_WRAPPER_PKG.GET_FARSI_MEANING_AND_COD_FUN(UPPER('COA_COST_CENTERS')
                                                         ,UPPER('LKP_COD_UNIT_CCNTR')
                                                         ,CC.LKP_COD_UNIT_CCNTR) AS LKP_COD_UNIT
      ,CC.DAT_STR_CCNTR
      ,TO_CHAR(CC.DAT_STR_CCNTR
              ,'YYYY/MM/DD HH24:MI:SS'
              ,'NLS_CALENDAR=PERSIAN') AS DAT_STR_CCNTR_H
      ,CC.DAT_END_CCNTR
      ,TO_CHAR(CC.DAT_END_CCNTR
              ,'YYYY/MM/DD HH24:MI:SS'
              ,'NLS_CALENDAR=PERSIAN') AS DAT_END_CCNTR_H
      ,CC.NUM_EMPL_CCNTR
      ,APPS.MAM_WRAPPER_PKG.GET_FARSI_MEANING_AND_COD_FUN(UPPER('COA_COST_CENTERS')
                                                         ,UPPER('LKP_TYP_AREA_CCNTR')
                                                         ,CC.LKP_TYP_AREA_CCNTR) AS LKP_TYP_AREA
      ,CC.NUM_SEQ_CCNTR
      ,CC.NUM_LEV_CCNTR
      ,CC.QTY_ALC_CCNTR
      ,APPS.MAM_WRAPPER_PKG.GET_FARSI_MEANING_AND_COD_FUN(UPPER('COA_COST_CENTERS')
                                                         ,UPPER('LKP_TYP_GRP_CCNTR')
                                                         ,CC.LKP_TYP_GRP_CCNTR) AS LKP_TYP_GRP
      ,APPS.MAM_WRAPPER_PKG.GET_FARSI_MEANING_AND_COD_FUN(UPPER('COA_COST_CENTERS')
                                                         ,UPPER('LKP_COD_ALC_CCNTR')
                                                         ,CC.LKP_COD_ALC_CCNTR) AS LKP_COD_ALC
      ,CC.NUM_DCM_CCNTR
      ,CC.DAT_DCM_CCNTR
      ,TO_CHAR(CC.DAT_DCM_CCNTR
              ,'YYYY/MM/DD HH24:MI:SS'
              ,'NLS_CALENDAR=PERSIAN') AS DAT_DCM_CCNTR_H
      ,CC.QTY_IN_ORD_CCNTR
      ,CC.QTY_OUT_ORD_CCNTR
      ,CC.AMN_ORD_CCNTR
      ,CC.EXPIT_COD_EXP_EXPIT
      ,CC.CCNTR_COD_CC_CCNTR
      ,CC.ITEM_ITEM_ID
      ,CC.ITEM_ITEM_ID_FOR
      ,CC.NUM_CONTRACT_CCNTR
      ,CC.QTY_IN_CCNTR
      ,CC.QTY_OUT_CCNTR
      ,CC.THPRT_COD_THPRT
      ,CC.AMN_REMORD_CCNTR
      ,APPS.MAM_WRAPPER_PKG.GET_FARSI_MEANING_AND_COD_FUN(UPPER('COA_COST_CENTERS')
                                                         ,UPPER('LKP_TYP_ACT_CCNTR')
                                                         ,CC.LKP_TYP_ACT_CCNTR) AS LKP_TYP_ACT
      ,CC.NAM_ABRV_CCNTR
      ,CC.FLG_SAL_CCNTR
  FROM COA.COA_COST_CENTERS CC

 WHERE 1 = 1
   AND APPS.MAM_WRAPPER_PKG.REPLACE_STRING(CC.DES_CC_CCNTR) LIKE
       APPS.MAM_WRAPPER_PKG.REPLACE_STRING('%&DES_CC_CCNTR%')
