SELECT T.ITEM_SUBSTITUTION_ID
      ,T.ITEM_ID_MITMS
      ,APPS.MAM_ITEMS_CTRL_PKG.GET_DESCRIPTION(P_ITEM_ID => T.ITEM_ID_MITMS) AS ITEM_FROM
      ,APPS.MAM_ITEMS_FLD_PKG.GET_DES_US_ITEM(P_ITEM_ID => T.ITEM_ID_MITMS) AS DES_US_ITEM_FROM
      ,T.ITEM_ID_SUBSTITUTE_MITMS
      ,APPS.MAM_ITEMS_CTRL_PKG.GET_DESCRIPTION(P_ITEM_ID => T.ITEM_ID_SUBSTITUTE_MITMS) AS ITEM_TO
      ,APPS.MAM_ITEMS_FLD_PKG.GET_DES_US_ITEM(P_ITEM_ID => T.ITEM_ID_SUBSTITUTE_MITMS) AS DES_US_ITEM_TO
      ,T.CREATE_DATE
      ,T.CREATE_BY_DB_USER
      ,T.CREATE_BY_APP_USER
      ,T.LAST_UPDATE_DATE
      ,T.LAST_UPDATE_BY_DB_USER
      ,T.LAST_UPDATE_BY_APP_USER
      ,T.LAST_CHANGE_TS
      ,T.MODULE_NAME
      ,T.OS_USERNAME
      ,T.ATTACH_ID
  FROM MAM.MAM_ITEM_SUBSTITUTIONS T
