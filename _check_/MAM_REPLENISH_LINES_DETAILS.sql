;
SELECT RLD.REPLENISH_LINES_DETAIL_ID
      ,RLD.MREQL_REQUEST_LINE_ID
      ,APPS.MAM_ITEMS_FLD_PKG.GET_COD_ITEM(P_ITEM_ID => APPS.MAM_REQUEST_LINES_FLD_PKG.GET_ITEM_ITEM_ID(P_REQUEST_LINE_ID => RLD.MREQL_REQUEST_LINE_ID)) AS COD_ITEM
      ,APPS.MAM_REQUEST_HEADERS_FLD_PKG.GET_NUM_REQUEST_MREQH(P_REQUEST_HEADER_ID => APPS.MAM_REQUEST_LINES_FLD_PKG.GET_MREQH_REQUEST_HEADER_ID(P_REQUEST_LINE_ID => RLD.MREQL_REQUEST_LINE_ID)) AS NUM_REQUEST
      ,RLD.MREPL_REPLENISH_LINE_ID
      ,APPS.MAM_REPLENISH_HEADERS_FLD_PKG.GET_NUM_REPLENISHMENT_MREPH(P_REPLENISH_HEADER_ID => APPS.MAM_REPLENISH_LINES_FLD_PKG.GET_MREPH_REPLENISH_HEADER_ID(P_REPLENISH_LINE_ID => RLD.MREPL_REPLENISH_LINE_ID)) AS NUM_REPLENISHMENT
      ,RLD.QTY_REPLENISH_MREPD
      ,RLD.ATTACH_ID
      ,RLD.LAST_UPDATE_BY_APP_USER
      ,RLD.LAST_UPDATE_BY_DB_USER
      ,RLD.LAST_UPDATE_DATE
      ,RLD.CREATE_BY_APP_USER
      ,RLD.CREATE_BY_DB_USER
      ,RLD.CREATE_DATE
  FROM MAM.MAM_REPLENISH_LINES_DETAILS RLD
 WHERE 1 = 1
   AND RLD.MREQL_REQUEST_LINE_ID IN (&REQUEST_LINE_ID)
--   AND RLD.MREPL_REPLENISH_LINE_ID IN (&REPLENISH_LINE_ID)
