SELECT (SELECT APPS.MAM_ITEMS_CTRL_PKG.GET_DESCRIPTION(P_ITEM_ID => S.ITEM_ITEM_ID)
          FROM MAM.MAM_SERIAL_NUMBERS S
         WHERE S.SERIAL_NUMBER_ID = RS.MSER_SERIAL_NUMBER_ID) AS ITEM
