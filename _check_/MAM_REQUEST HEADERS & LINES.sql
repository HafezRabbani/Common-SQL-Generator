SELECT --
 X.MATERIAL_TRANSACTION_ID
,X.ID_TRANSFER_MTRAN AS LINKED_XID
,X.MTYP_TRANSACTION_TYPE_ID AS TT
,APPS.MAM_ITEMS_FLD_PKG.GET_COD_ITEM(P_ITEM_ID => X.ITEM_ITEM_ID_FOR) AS I
,X.MSINV_NAM_SUB_INVENTORY_MSIFOR || ': ' ||
 (SELECT N.DES_MSINV
    FROM MAM.MAM_SUB_INVENTORIES N
   WHERE N.NAM_SUB_INVENTORY_MSINV = X.MSINV_NAM_SUB_INVENTORY_MSIFOR) AS SUB_INVENTORY
,(SELECT L.COD_LOCATOR_MSLOC
    FROM MAM.MAM_SUB_INVENTORY_LOCATORS L
   WHERE L.SUB_INVENTORY_LOCATOR_ID = X.MSLOC_SUB_INVENTORY_LOCATORFOR) AS COD_LOCATOR_MSLOC
,X.SPINV_NUM_SRL_SPINV AS SPINV
,X.ORPYD_ORPYM_NUM_ORD_PYM_ORPYM AS ORPYD
,TO_CHAR(X.DAT_TRANSACTION_MTRAN
        ,'YYYY/MM/DD HH24:MI:SS'
        ,'NLS_CALENDAR=PERSIAN') AS D
,(SELECT RX.NUM_RECEIPT_AP_MRCV || ','
    FROM MAM.MAM_RCV_TRANSACTIONS RX
   WHERE RX.MTRAN_MATERIAL_TRANSACTION_ID = X.MATERIAL_TRANSACTION_ID) AS NUM_RECEIPT_AP_MRCV
,(SELECT RX.RCV_TRANSACTION_ID || ','
    FROM MAM.MAM_RCV_TRANSACTIONS RX
   WHERE RX.MTRAN_MATERIAL_TRANSACTION_ID = X.MATERIAL_TRANSACTION_ID) AS RCV_TRANSACTION_ID
,X.QTY_PRIMARY_MTRAN AS QTY
,APPS.MAM_EXTERNAL_SYSTEMS_DESC_PKG.GET_BFS_THIRD_PARTIES(P_COD_THPRT => X.THPRT_COD_THPRT) AS THIRD_PARTY
,X.*
  FROM MAM.MAM_MATERIAL_TRANSACTIONS X
 WHERE 1 = 1
      
   AND X.MREQL_REQUEST_LINE_ID IN
       ( --
        SELECT L.REQUEST_LINE_ID
          FROM MAM.MAM_REQUEST_LINES L
         WHERE 1 = 1 --
           AND ( --
                EXISTS ( --
                        SELECT NULL
                          FROM MAM.MAM_REQUEST_HEADERS H
                         WHERE H.REQUEST_HEADER_ID = L.MREQH_REQUEST_HEADER_ID
                              --AND H.NUM_REQUEST_MREQH LIKE TRIM('&NUM_REQUEST_LIKE')
                           AND H.NUM_REQUEST_MREQH IN (&NUM_REQUEST_IN)
                        --
                        )
               --
               ) --
        )
 ORDER BY X.DAT_TRANSACTION_MTRAN, X.ITEM_ITEM_ID_FOR, X.QTY_PRIMARY_MTRAN
