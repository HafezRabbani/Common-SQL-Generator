SELECT RAX.REQ_ACT_TRANSACTION_ID
      ,RAX.MORQA_REQ_ACT_ID
      ,RAX.MTRAN_MATERIAL_TRANSACTION_ID
      ,MOR_REQ_ACTS_FLD_PKG.GET_MORRQ_REQUEST_ID(P_REQ_ACT_ID => RAX.MORQA_REQ_ACT_ID) AS REQUEST_ID
      ,RAX.CREATE_DATE
      ,APPS.MAM_HEJRI_DATE_HANDLING_PKG.TO_HEJRI_STRING(P_DATE => RAX.CREATE_DATE) AS CREATE_DATE_H
      ,RAX.CREATE_BY_DB_USER
      ,RAX.CREATE_BY_APP_USER
      ,RAX.LAST_UPDATE_DATE
      ,APPS.MAM_HEJRI_DATE_HANDLING_PKG.TO_HEJRI_STRING(P_DATE => RAX.LAST_UPDATE_DATE) AS LAST_UPDATE_DATE_H
      ,RAX.LAST_UPDATE_BY_DB_USER
      ,RAX.LAST_UPDATE_BY_APP_USER
      ,RAX.LAST_CHANGE_TS
      ,RAX.MODULE_NAME
      ,RAX.OS_USERNAME
      ,RAX.ATTACH_ID
  FROM MOR.MOR_REQ_ACT_TRANSACTIONS RAX
 WHERE 1 = 1
   AND RAX.CREATE_DATE > TRUNC(SYSDATE)
