SELECT AR.NAM_KEY_FIELD_MLAFR
      ,AR.NAM_VAL_MLAFR
      ,X.DAT_TRANSACTION_MTRAN
      ,AR.CREATE_DATE
       
      ,L.CREATE_DATE
      ,TRUNC((AR.CREATE_DATE - L.CREATE_DATE) * 100000) AS LATENCY
  FROM MAM.MAM_LOGS L
 INNER JOIN MAM.MAM_LOG_AFFECTED_RECORDS AR
    ON AR.MLAFR_LOG_ID = L.LOG_ID
 INNER JOIN MAM.MAM_MATERIAL_TRANSACTIONS X
    ON AR.NAM_VAL_MLAFR = X.MATERIAL_TRANSACTION_ID
 WHERE 1 = 1
      --    AND L.NAM_CALLER_ROUTINE_MLOGS = 'APP_MAM_PMS_PKG.INS_MTRAN_PRC'
   AND L.CREATE_DATE > TRUNC(SYSDATE)
      --    apps."MAM_HEJRI_DATE_HANDLING_PKG".TO_DATE_YYYY_MM_DD_HH24_MI_SS(P_HEJRI_STRING => '1404/11/04 11')
   AND TRUNC((AR.CREATE_DATE - L.CREATE_DATE) * 100000) > 1
--
;

SELECT L.LOG_ID
      ,R.CREATE_DATE
      ,L.CREATE_DATE
      ,TRUNC((R.CREATE_DATE - L.CREATE_DATE) * 100000) AS LATENCY
  FROM MAM.MAM_LOGS L
 INNER JOIN MAM.MAM_LOG_RESPONSES R
    ON R.LOG_ID_MLOGR = L.LOG_ID
 WHERE 1 = 1
      --    AND L.NAM_CALLER_ROUTINE_MLOGS = 'APP_MAM_PMS_PKG.INS_MTRAN_PRC'
   AND L.CREATE_DATE > TRUNC(SYSDATE)
      --    apps."MAM_HEJRI_DATE_HANDLING_PKG".TO_DATE_YYYY_MM_DD_HH24_MI_SS(P_HEJRI_STRING => '1404/11/04 11')
   AND TRUNC((R.CREATE_DATE - L.CREATE_DATE) * 100000) > 1
--
;

